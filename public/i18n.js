  const DICT = { en, it, es, fr, de, pt };
  const LOCALES = { en: 'en-GB', it: 'it-IT', es: 'es-ES', fr: 'fr-FR', de: 'de-DE', pt: 'pt-PT' };
  const LIST = [
    { code: 'en', name: 'English' }, { code: 'it', name: 'Italiano' }, { code: 'es', name: 'Español' },
    { code: 'fr', name: 'Français' }, { code: 'de', name: 'Deutsch' }, { code: 'pt', name: 'Português' },
  ];
  let code = 'en';
  const listeners = [];

  function t(key, vars) {
    let s = DICT[code] && DICT[code][key];
    if (s === undefined) s = en[key];
    if (s === undefined) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }
  function apply(root) {
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    r.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    r.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  }
  function set(next) {
    code = DICT[next] ? next : 'en';
    document.documentElement.lang = code;
    apply();
    listeners.forEach((fn) => { try { fn(code); } catch (e) { /* ignore */ } });
    return code;
  }
  window.RTV_I18N = {
    t, set, apply, languages: LIST, get locale() { return LOCALES[code] || 'en-GB'; },
    get lang() { return code; },
    onChange(fn) { listeners.push(fn); },
  };
